"""Write the OpenSCAD sources, the preview images, and the 3MF mesh."""

import json
import re
import shutil
import subprocess
from pathlib import Path

import cv2
import numpy as np

from cookie_cutter.geometry import polygon_area, polygon_perimeter
from cookie_cutter.outline import PreparedCutters, prepare_cutters
from cookie_cutter.paths import (
    BUILD_INFO,
    MAIN_SCAD,
    MATCH_PNG,
    MODEL_3MF,
    MODELS,
    OUTLINES_SCAD,
    PREVIEW_PNG,
    PROFILE_SCAD,
    SCAD_DIR,
)
from cookie_cutter.profile import SCAD_PARAMETERS, rim_outer_mm

MAIN_SOURCE = """// Generated by python -m cookie_cutter.generate. Do not edit.
// Cat (left) and dog (right). The flange is on the bed and the cutting edge faces up.
include <cutter_profile.scad>
include <outlines.scad>

cutter(cat_points);
cutter(dog_points);
"""

# OpenSCAD's zero rotation looks straight down. A small tilt keeps the
# silhouettes readable and shows the rim and the stepped wall.
PREVIEW_CAMERA = "0,0,0,36,0,8,0"
PREVIEW_SIZE = "1600,1000"


def outlines_source(prepared: PreparedCutters) -> str:
    lines = [
        "// Generated by python -m cookie_cutter.generate. Do not edit.",
        "// Inner cookie outlines in millimetres, wound counter-clockwise.",
        f"// scale_mm_per_px = {prepared.scale_mm_per_px:.8f}",
        f"// separation_shift_mm = {prepared.separation_shift_mm:.4f}",
        "",
    ]
    for shape in prepared.shapes:
        lines.append(f"{shape.name}_points = [")
        for x, y in shape.millimeters:
            lines.append(f"    [{x:.6f}, {y:.6f}],")
        lines.append("];")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def write_scad(directory: Path, prepared: PreparedCutters, copy_profile: bool = False) -> Path:
    directory.mkdir(parents=True, exist_ok=True)
    if copy_profile:
        shutil.copyfile(PROFILE_SCAD, directory / "cutter_profile.scad")
    (directory / "outlines.scad").write_text(outlines_source(prepared))
    main = directory / "cat_dog_cookie_cutters.scad"
    main.write_text(MAIN_SOURCE)
    return main


def run_openscad(args: list[str], timeout: int = 180) -> str:
    completed = subprocess.run(args, capture_output=True, text=True, timeout=timeout)
    log = (completed.stdout or "") + (completed.stderr or "")
    if completed.returncode != 0:
        raise RuntimeError(log.strip() or f"openscad exited {completed.returncode}")
    return log


def export_3mf(scad_path: Path, dest: Path) -> str:
    dest.parent.mkdir(parents=True, exist_ok=True)
    return run_openscad(
        ["openscad", "-o", str(dest), "--export-format", "3mf", str(scad_path)]
    )


def export_preview(scad_path: Path, dest: Path) -> str:
    dest.parent.mkdir(parents=True, exist_ok=True)
    return run_openscad(
        [
            "openscad",
            "-o",
            str(dest),
            "--render",
            f"--imgsize={PREVIEW_SIZE}",
            "--colorscheme=Cornfield",
            "--projection=p",
            "--autocenter",
            "--viewall",
            f"--camera={PREVIEW_CAMERA}",
            str(scad_path),
        ]
    )


def save_match_figure(prepared: PreparedCutters, dest: Path) -> None:
    from cookie_cutter.outline import load_mask

    mask = load_mask()
    height, width = mask.shape
    reference = np.full((height, width, 3), 255, np.uint8)
    reference[mask > 0] = (0, 0, 0)

    model = np.zeros((height, width), np.uint8)
    for shape in prepared.shapes:
        ring = np.round(shape.pixels).astype(np.int32).reshape(-1, 1, 2)
        cv2.fillPoly(model, [ring], 255)
    model_bgr = np.full((height, width, 3), 255, np.uint8)
    model_bgr[model > 0] = (0, 0, 0)

    difference = np.full((height, width, 3), 255, np.uint8)
    both = (mask > 0) & (model > 0)
    difference[both] = (40, 40, 40)
    difference[(model > 0) & ~both] = (0, 0, 210)
    difference[(mask > 0) & ~both] = (210, 80, 0)

    panels = []
    titles = [
        "template",
        "cutter outline",
        "difference (red extra, blue missing)",
    ]
    for image, title in zip((reference, model_bgr, difference), titles):
        panel = cv2.resize(image, (width // 2, height // 2), interpolation=cv2.INTER_AREA)
        cv2.putText(
            panel,
            title,
            (12, 28),
            cv2.FONT_HERSHEY_SIMPLEX,
            0.7,
            (30, 30, 30),
            2,
            cv2.LINE_AA,
        )
        panels.append(panel)
    gap = np.full((panels[0].shape[0], 8, 3), 255, np.uint8)
    figure = np.hstack([panels[0], gap, panels[1], gap, panels[2]])
    dest.parent.mkdir(parents=True, exist_ok=True)
    if not cv2.imwrite(str(dest), figure):
        raise RuntimeError(f"could not write {dest}")


def estimated_wall_volume(prepared: PreparedCutters) -> float:
    """Straight-wall volume, ignoring the rounded outside corners."""
    edge = SCAD_PARAMETERS["edge_thickness"]
    lower = SCAD_PARAMETERS["lower_wall_thickness"]
    total = 0.0
    for shape in prepared.shapes:
        length = polygon_perimeter(shape.millimeters)
        total += length * edge * SCAD_PARAMETERS["total_height"]
        total += length * (lower - edge) * SCAD_PARAMETERS["lower_wall_height"]
        total += length * SCAD_PARAMETERS["rim_extension"] * SCAD_PARAMETERS["rim_thickness"]
    return total


def solid_cookie_volume(prepared: PreparedCutters) -> float:
    area = sum(abs(polygon_area(shape.millimeters)) for shape in prepared.shapes)
    return area * SCAD_PARAMETERS["total_height"]


def _shape_record(shape, scale: float) -> dict:
    span = shape.millimeters.max(axis=0) - shape.millimeters.min(axis=0)
    return {
        "name": shape.name,
        "points": int(len(shape.pixels)),
        "iou": round(float(shape.iou), 6),
        "width_mm": round(float(span[0]), 3),
        "height_mm": round(float(span[1]), 3),
        "pixel_height": round(float(span[1] / scale), 3),
    }


def build_info(prepared: PreparedCutters) -> dict:
    inners = np.vstack([shape.millimeters for shape in prepared.shapes])
    inner_span = inners.max(axis=0) - inners.min(axis=0)
    outer = rim_outer_mm()
    footprint = inner_span + 2.0 * outer
    return {
        "template": "references/template.png",
        "scale_mm_per_px": round(prepared.scale_mm_per_px, 8),
        "original_gap_mm": round(prepared.original_gap_mm, 3),
        "separation_shift_mm": round(prepared.separation_shift_mm, 3),
        "footprint_mm": [round(float(footprint[0]), 3), round(float(footprint[1]), 3)],
        "height_mm": SCAD_PARAMETERS["total_height"],
        "shapes": [_shape_record(shape, prepared.scale_mm_per_px) for shape in prepared.shapes],
    }


def openscad_is_simple(log: str) -> bool:
    return re.search(r"Simple:\s+yes", log) is not None


def generate(prepared: PreparedCutters | None = None) -> PreparedCutters:
    prepared = prepare_cutters() if prepared is None else prepared
    SCAD_DIR.mkdir(parents=True, exist_ok=True)
    write_scad(SCAD_DIR, prepared, copy_profile=False)
    MODELS.mkdir(parents=True, exist_ok=True)
    save_match_figure(prepared, MATCH_PNG)
    log = export_3mf(MAIN_SCAD, MODEL_3MF)
    if not openscad_is_simple(log):
        raise RuntimeError("OpenSCAD did not report a simple mesh:\n" + log)
    export_preview(MAIN_SCAD, PREVIEW_PNG)
    info = build_info(prepared)
    info["estimated_wall_volume_mm3"] = round(estimated_wall_volume(prepared), 1)
    BUILD_INFO.write_text(json.dumps(info, indent=2) + "\n")
    return prepared


def main() -> None:
    prepared = generate()
    info = json.loads(BUILD_INFO.read_text())
    print(f"wrote {MODEL_3MF.relative_to(MODEL_3MF.parents[1])}")
    print(f"wrote {PREVIEW_PNG.name} and {MATCH_PNG.name}")
    for shape in info["shapes"]:
        print(
            f"  {shape['name']}: IoU {shape['iou']:.4f}, "
            f"{shape['width_mm']:.1f} x {shape['height_mm']:.1f} mm, "
            f"{shape['points']} points"
        )
    print(
        f"  artwork gap {info['original_gap_mm']:.2f} mm, "
        f"extra shift each way {info['separation_shift_mm']:.2f} mm"
    )
    print(f"  footprint {info['footprint_mm'][0]:.1f} x {info['footprint_mm'][1]:.1f} mm")


if __name__ == "__main__":
    main()
